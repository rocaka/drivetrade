export function checkAnswers(questions: Question[], answers: Record<string, number>) {
  const answered = questions.filter((q) => Number.isInteger(answers[q.id]));
  const correct = questions.filter((q) => answers[q.id] === q.answer);
  return {
    score: questions.length ? (correct.length / questions.length) * 100 : 0,
    complete: answered.length === questions.length,
    criticalPassed: questions.filter((q) => q.critical).every((q) => answers[q.id] === q.answer),
    wrong: questions.filter((q) => answers[q.id] !== q.answer).map((q) => q.id),
  };
}
