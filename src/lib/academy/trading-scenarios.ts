function choice(id: string, dimension: Dimension, weight: number, p: Pick): ScenarioTask {
  return { id, dimension, weight, prompt: p[0], options: p[1], answer: p[2], explanation: p[3] };
}
export function makeScenario(index: number, formal = false): Scenario {
  const spec = specs[index % specs.length],
    equity = formal ? 12000 + (index % 4) * 2000 : 10000,
    reserve = formal ? 3 + (index % 3) : 2;
  return {
    id: `trade-${formal ? "formal" : "practice"}-${index + 1}`,
    curriculumVersion: CURRICULUM_VERSION,
    title: spec.title,
    summary: spec.summary,
    lessonId: `trade-lesson-${spec.lesson}`,
    chain: "模拟现货",
    equity,
    reserve,
    budgetPct: 1,
    facts: spec.facts,
    formal,
    tasks: [
      {
        id: "budget",
        dimension: "risk",
        weight: 60,
        prompt: `本题权益${equity}，教学全损上限1%，必要成本${reserve}。最大本金投入是多少训练美元？`,
        numberAnswer: equity * 0.01 - reserve,
        explanation: `${equity}×1%−${reserve}=${equity * 0.01 - reserve}。仅为本题教学设置，止损不能放大全损上限。`,
      },
      choice("risk", "risk", 40, spec.risk),
      choice("decision", "execution", 100, spec.decision),
      choice("fact", "review", 30, spec.fact),
      choice("cause", "review", 30, spec.cause),
      choice("correction", "review", 40, spec.correction),
    ],
  };
}
export const PRACTICE_SCENARIOS = specs.map((_, i) => makeScenario(i));
export const FORMAL_SCENARIOS = Array.from({ length: 8 }, (_, i) => makeScenario(i, true));
